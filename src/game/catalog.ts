export function spawnActor(spawn: Spawn): Actor {
  const t = TEMPLATES[spawn.template];
  const hp = maxHp(t.body, 1);
  return {
    id: spawn.id,
    template: t.template,
    name: spawn.name ?? t.name,
    title: t.title,
    portrait: t.portrait,
    sprite: t.sprite,
    scale: t.scale,
    mapId: spawn.map,
    x: spawn.x,
    y: spawn.y,
    home: { mapId: spawn.map, x: spawn.x, y: spawn.y },
    hp,
    maxHp: hp,
    ap: 0,
    maxAp: maxAp(t.attrs.finesse),
    attrs: { ...t.attrs },
    skills: { ...t.skills },
    tags: [],
    nodes: structuredClone(t.nodes),
    faction: t.faction,
    hostile: spawn.hostile ?? t.hostile,
    aggro: spawn.aggro ?? t.aggro,
    alive: true,
    companion: false,
    convo: spawn.convo ?? t.convo,
    downConvo: t.downConvo,
    weapon: t.weapon,
    stunned: false,
    polymorphic: Boolean(t.polymorphic),
    tier: t.tier,
    vision: t.vision,
  };
}
